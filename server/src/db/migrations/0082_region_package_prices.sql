-- 区域包裹价格配置：按州（region_code）隔离的 postcode/suburb 派送单价表
-- pre_price 存上一次的价格，价格调整时由后端自动滚存
-- courier_price 为派送员价格，未显式给值时默认取 price - 0.25
-- vendor_code 存 iMile 供应商编码（SRM…），vendor_name 存页面展示的供应商名称
CREATE TABLE IF NOT EXISTS "region_package_prices" (
  "id" uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  "region_code" varchar(16) NOT NULL,
  "postcode" varchar(16) NOT NULL,
  "suburb" varchar(128) NOT NULL,
  "price" double precision NOT NULL,
  "pre_price" double precision,
  "courier_price" double precision NOT NULL,
  "vendor_code" varchar(64) NOT NULL DEFAULT '',
  "vendor_name" varchar(255) NOT NULL DEFAULT '',
  "created_at" timestamptz NOT NULL DEFAULT now(),
  "updated_at" timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS "region_package_prices_region_area_unique"
  ON "region_package_prices" ("region_code", "postcode", "suburb");

